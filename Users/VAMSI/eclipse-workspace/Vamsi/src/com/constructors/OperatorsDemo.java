package com.constructors;

public class OperatorsDemo {
	
	public static void main(String[]args) {
		
		int a=100;
		int b=200;
		int c=10;
		System.out.println(a<b&&b>c);
		System.out.println(a>b&&b>c);
		System.out.println(a<b&&b<c);
		System.out.println(a<b&&b<c);
		
		
		System.out.println(a<b||b>c);
		System.out.println(a>b||b>c);
		System.out.println(a<b||b<c);
		System.out.println(a>b||b<c);
		 
		System.out.println(72&78);
		
	
	
		
	}

}
