package com.constructors;

public class SwapDemo {
	


	

	public static void main(String[] args) {

		int a=10;
		int b=20;
		
		System.out.println("A Value :"+a);
		System.out.println("B Value :"+b);
		
		
		a=a+b;
		b=a-b;
		a=a-b;

		
		
		System.out.println("----------After  Swapping-----------");
		
		System.out.println("A Value :"+a);
		System.out.println("B Value :"+b);
		
		 
		

	}

}
